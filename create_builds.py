#!/usr/bin/env python3
"""Create Buildx Bake files and merge per-architecture image manifests."""

import datetime
import json
import os
import shlex
import subprocess
import sys
from pathlib import Path
from typing import Any

PLATFORMS = ["linux/amd64", "linux/arm64"]
ARCHITECTURES = ["amd64", "arm64"]
TARGETS = ["pyenv", "tox-base"]
VARIANTS = ["alpine-3.23", "debian-bookworm", "ubuntu-noble"]
VARIANTS += ["alpine-3.24", "debian-trixie", "ubuntu-resolute"]
# Which distro version gets the distro name tag
DISTRO_DEFAULT_VERSIONS = {
    "alpine": "3.24",
    "debian": "trixie",
    "ubuntu": "resolute",
}
BUILD_PYTHON_VERSIONS = "3.12 3.13 3.14 3.15"


def get_build_date() -> datetime.date:
    """Use a workflow-provided date so build and manifest tags stay consistent."""
    build_date = os.environ.get("BUILD_DATE")
    if build_date:
        return datetime.date.fromisoformat(build_date)
    return datetime.datetime.now(datetime.UTC).date()


def get_cache_epoch(build_date: datetime.date) -> str:
    """Return a weekly cache refresh key unless one was explicitly provided."""
    cache_epoch = os.environ.get("CACHE_EPOCH")
    if cache_epoch:
        return cache_epoch
    iso_year, iso_week, _ = build_date.isocalendar()
    return f"{iso_year}-W{str(iso_week).zfill(2)}"


def target_name(target: str, variant: str) -> str:
    """Return the Bake target name for an image and distro variant."""
    return f"{target}-{variant.replace('.', '')}"


def image_tags(reponame: str, target: str, variant: str, build_date: datetime.date) -> list[str]:
    """Return stable and dated image tags for a variant."""
    distro, version = variant.split("-")
    tags = []
    if version == DISTRO_DEFAULT_VERSIONS[distro]:
        tags.extend(
            [
                f"{reponame}/{target}:{distro}",
                f"{reponame}/{target}:{distro}-{build_date.isoformat()}",
            ]
        )
    tags.extend(
        [
            f"{reponame}/{target}:{distro}-{version}",
            f"{reponame}/{target}:{distro}-{version}-{build_date.isoformat()}",
        ]
    )
    return tags


def print_bakefile(reponame: str, target: str) -> None:
    """Print a cache-aware Bake file for one target or both targets."""
    build_date = get_build_date()
    cache_epoch = get_cache_epoch(build_date)
    selected_targets = TARGETS if target == "all" else [target]
    bake_target_names = [
        target_name(image_target, variant)
        for image_target in selected_targets
        for variant in VARIANTS
    ]

    print(
        f'''// Generated by create_builds.py. Set BUILD_ARCH to amd64 or arm64 for a native build.
// Set PUSH_BY_DIGEST=true for CI's per-architecture manifest workflow.
// Set CACHE_PUSH=true to publish the tox-base intermediate-stage cache.

variable "BUILD_ARCH" {{ default = "" }}
variable "PUSH_BY_DIGEST" {{ default = false }}
variable "CACHE_PUSH" {{ default = false }}
variable "CACHE_REPO" {{ default = "{reponame}/buildcache" }}
variable "CACHE_EPOCH" {{ default = "{cache_epoch}" }}

group "default" {{
    targets = {json.dumps(bake_target_names)}
}}'''
    )

    for image_target in selected_targets:
        group_targets = [target_name(image_target, variant) for variant in VARIANTS]
        print(
            f'''
group "{image_target}" {{
    targets = {json.dumps(group_targets)}
}}'''
        )

    for image_target in selected_targets:
        for variant in VARIANTS:
            distro, version = variant.split("-")
            tags = image_tags(reponame, image_target, variant, build_date)
            dockerfile = f"Dockerfile_{distro}"
            cache_from = [
                f"type=registry,ref=${{CACHE_REPO}}:{variant}-{architecture}"
                for architecture in ARCHITECTURES
            ]
            cache_to_target = (
                f"type=registry,ref=${{CACHE_REPO}}:{variant}-${{BUILD_ARCH}},"
                "mode=max,image-manifest=true,oci-mediatypes=true"
            )
            cache_to = (
                f'CACHE_PUSH && BUILD_ARCH != "" ? ["{cache_to_target}"] : []'
                if image_target == "tox-base"
                else "[]"
            )

            print(
                f'''
target "{target_name(image_target, variant)}" {{
    dockerfile = "{dockerfile}"
    platforms = BUILD_ARCH == "" ? {json.dumps(PLATFORMS)} : ["linux/${{BUILD_ARCH}}"]
    target = "{image_target}"
    args = {{
        IMAGE_VERSION = "{version}"
        BUILD_PYTHON_VERSIONS = "{BUILD_PYTHON_VERSIONS}"
        CACHE_EPOCH = "${{CACHE_EPOCH}}"
    }}
    cache-from = {json.dumps(cache_from)}
    cache-to = {cache_to}
    tags = PUSH_BY_DIGEST ? [] : {json.dumps(tags)}
    output = BUILD_ARCH != "" && PUSH_BY_DIGEST ? ["type=image,name={reponame}/{image_target},push-by-digest=true,name-canonical=true,push=true"] : []
}}'''
            )


def read_metadata(path: Path) -> dict[str, Any]:
    """Read and validate a Buildx metadata file."""
    try:
        with path.open(encoding="utf-8") as metadata_file:
            metadata = json.load(metadata_file)
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"Could not read Buildx metadata file {path}: {error}") from error
    if not isinstance(metadata, dict):
        raise ValueError(f"Buildx metadata file {path} must contain a JSON object")
    return metadata


def merge_commands(reponame: str, metadata_paths: list[Path], build_date: datetime.date) -> list[list[str]]:
    """Build imagetools commands from metadata, validating all targets first."""
    metadata_files = [(path, read_metadata(path)) for path in metadata_paths]
    commands = []
    for target in TARGETS:
        for variant in VARIANTS:
            name = target_name(target, variant)
            sources = []
            for path, metadata in metadata_files:
                target_metadata = metadata.get(name)
                if not isinstance(target_metadata, dict):
                    raise ValueError(f"Buildx metadata file {path} is missing target {name!r}")
                digest = target_metadata.get("containerimage.digest")
                if not isinstance(digest, str) or not digest.startswith("sha256:"):
                    raise ValueError(
                        f"Buildx metadata file {path} has no valid containerimage.digest for {name!r}"
                    )
                sources.append(f"{reponame}/{target}@{digest}")

            command = ["docker", "buildx", "imagetools", "create"]
            for tag in image_tags(reponame, target, variant, build_date):
                command.extend(["--tag", tag])
            commands.append(command + sources)
    return commands


def merge_images(reponame: str, metadata_paths: list[Path], dry_run: bool = False) -> None:
    """Merge per-architecture digests and assign the standard image tags."""
    if len(metadata_paths) != len(ARCHITECTURES):
        raise ValueError(f"merge requires one metadata file for each architecture ({', '.join(ARCHITECTURES)})")
    commands = merge_commands(reponame, metadata_paths, get_build_date())
    for command in commands:
        if dry_run:
            print(shlex.join(command))
        else:
            subprocess.run(command, check=True)


def main(arguments: list[str]) -> int:
    """CLI entry point."""
    reponame = os.environ.get("DHUBREPO")
    if not reponame:
        print("Define DHUBREPO", file=sys.stderr)
        return 1
    if not arguments:
        print(f"Specify target, one of: {', '.join(TARGETS + ['all', 'merge'])}", file=sys.stderr)
        return 1

    command = arguments[0]
    if command in TARGETS + ["all"]:
        if len(arguments) != 1:
            print(f"Unexpected arguments for {command}", file=sys.stderr)
            return 1
        print_bakefile(reponame, command)
        return 0
    if command != "merge":
        print(f"Specify target, one of: {', '.join(TARGETS + ['all', 'merge'])}", file=sys.stderr)
        return 1

    merge_arguments = arguments[1:]
    dry_run = "--dry-run" in merge_arguments
    metadata_paths = [Path(argument) for argument in merge_arguments if argument != "--dry-run"]
    try:
        merge_images(reponame, metadata_paths, dry_run)
    except (ValueError, subprocess.CalledProcessError) as error:
        print(error, file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError):
            return error.returncode
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
